// --- Geographic Projection Helpers ---
// Calibrated for Tunisia coordinates: Lat [30.1, 37.6], Lng [7.4, 11.9]
export const TUNISIA_BOUNDS = {
  minLat: 30.1,
  maxLat: 37.6,
  minLng: 7.4,
  maxLng: 11.9,
};

export function latLngToMapCoords(
  lat: number,
  lng: number,
  viewWidth = 600,
  viewHeight = 900
): { x: number; y: number } {
  const normX = (lng - TUNISIA_BOUNDS.minLng) / (TUNISIA_BOUNDS.maxLng - TUNISIA_BOUNDS.minLng);
  // Invert Y because SVG/Canvas (0,0) is top-left while latitude increases northward
  const normY = (TUNISIA_BOUNDS.maxLat - lat) / (TUNISIA_BOUNDS.maxLat - TUNISIA_BOUNDS.minLat);

  return {
    x: normX * viewWidth,
    y: normY * viewHeight,
  };
}

export function mapCoordsToLatLng(
  x: number,
  y: number,
  viewWidth = 600,
  viewHeight = 900
): { lat: number; lng: number } {
  const normX = Math.max(0, Math.min(1, x / viewWidth));
  const normY = Math.max(0, Math.min(1, y / viewHeight));

  const lng = TUNISIA_BOUNDS.minLng + normX * (TUNISIA_BOUNDS.maxLng - TUNISIA_BOUNDS.minLng);
  const lat = TUNISIA_BOUNDS.maxLat - normY * (TUNISIA_BOUNDS.maxLat - TUNISIA_BOUNDS.minLat);

  return { lat, lng };
}

// --- Yield Calculation Engine for Tunisian Apiculture ---
export function calculatePredictedYield(
  site: HarvestSite,
  hiveCount: number,
  rainfallCondition: 'abundant' | 'normal' | 'drought' | 'severe_drought',
  colonyVigor: 'exceptional' | 'standard' | 'divided',
  chehiliOccurrence: boolean,
  waterStationProvided: boolean,
  varroaTreated: 'treated_certified' | 'standard' | 'untreated'
) {
  // Base potential per hive according to bioclimatic suitability and primary honey type
  let baseKg = 16.0;
  if (site.primaryHoneyOutput === 'citrus') baseKg = 24.0;
  else if (site.primaryHoneyOutput === 'heather_forest') baseKg = 19.0;
  else if (site.primaryHoneyOutput === 'eucalyptus') baseKg = 21.0;
  else if (site.primaryHoneyOutput === 'rosemary') baseKg = 17.5;
  else if (site.primaryHoneyOutput === 'thyme') baseKg = 13.0;
  else if (site.primaryHoneyOutput === 'sidr') baseKg = 14.5;
  else if (site.primaryHoneyOutput === 'carob') baseKg = 15.0;

  // Rainfall multiplier
  let rainFactor = 1.0;
  if (rainfallCondition === 'abundant') rainFactor = 1.28;
  else if (rainfallCondition === 'normal') rainFactor = 1.0;
  else if (rainfallCondition === 'drought') rainFactor = 0.68;
  else if (rainfallCondition === 'severe_drought') rainFactor = 0.42;

  // Colony vigor multiplier
  let vigorFactor = 1.0;
  if (colonyVigor === 'exceptional') vigorFactor = 1.25;
  else if (colonyVigor === 'standard') vigorFactor = 1.0;
  else if (colonyVigor === 'divided') vigorFactor = 0.65;

  // Heatwave (Chehili) stress
  let thermalStress = 1.0;
  if (chehiliOccurrence) {
    thermalStress = waterStationProvided ? 0.82 : 0.62;
  } else if (!waterStationProvided && site.waterAccessRadiusKm > 1.0) {
    thermalStress = 0.9;
  }

  // Varroa sanitary status
  let healthFactor = 1.0;
  if (varroaTreated === 'treated_certified') healthFactor = 1.1;
  else if (varroaTreated === 'standard') healthFactor = 1.0;
  else if (varroaTreated === 'untreated') healthFactor = 0.72;

  // Carrying capacity and hive density competition
  const capacityRatio = hiveCount / site.recommendedMaxHives;
  let densityPenalty = 1.0;
  let carryingCapacityStress: 'optimal' | 'moderate_competition' | 'overstocked' = 'optimal';

  if (capacityRatio > 1.6) {
    densityPenalty = 0.68;
    carryingCapacityStress = 'overstocked';
  } else if (capacityRatio > 1.1) {
    densityPenalty = 0.88;
    carryingCapacityStress = 'moderate_competition';
  }

  const finalKgPerHive = Math.max(
    2.5,
    Math.round(
      baseKg * rainFactor * vigorFactor * thermalStress * healthFactor * densityPenalty * 10
    ) / 10
  );

  const totalKg = Math.round(finalKgPerHive * hiveCount);
  const waxKg = Math.round(totalKg * 0.035 * 10) / 10;
  const propolisKg = Math.round(hiveCount * 0.12 * 10) / 10;

  // Price calculation in TND
  const flora = MELLIFEROUS_FLORA.find((f) => f.honeyType === site.primaryHoneyOutput);
  const pricePerKg = flora?.honeyProfile.avgPricePerKgTND || 50;
  const totalRevenueTND = Math.round(totalKg * pricePerKg);

  return {
    yieldPerHiveKg: finalKgPerHive,
    totalHoneyYieldKg: totalKg,
    waxYieldKg: waxKg,
    propolisYieldKg: propolisKg,
    estimatedRevenueTND: totalRevenueTND,
    carryingCapacityStress,
    pricePerKgTND: pricePerKg,
    moistureForecastPercent: chehiliOccurrence ? 16.2 : 17.5,
    factors: {
      basePotential: baseKg,
      rainImpactPct: Math.round((rainFactor - 1) * 100),
      vigorImpactPct: Math.round((vigorFactor - 1) * 100),
      thermalStressPct: Math.round((thermalStress - 1) * 100),
      densityPenaltyPct: Math.round((densityPenalty - 1) * 100),
      healthImpactPct: Math.round((healthFactor - 1) * 100),
    },
  };
}
